"""Redraws the Mizan icon (M + rising bars + wallet) as Android adaptive-icon
vector layers, cuts the legacy launcher PNGs from the artwork, and renders a
side-by-side preview to compare with it. See ADR 0021.

Geometry is in the artwork's pixels (1254x1254); the XML scales it into the
108dp adaptive canvas with a <group> transform.

From the repo root (needs Pillow):
    python app/tool/icon/make_icon.py docs/brand/icon.png         app/android/app/src/main/res <preview folder>
"""
import math
import os
import sys

from PIL import Image, ImageDraw

SRC = sys.argv[1]          # the user's icon PNG
RES = sys.argv[2]          # app/android/app/src/main/res
OUT = sys.argv[3]          # preview folder

# --- Shapes, in source pixels -------------------------------------------
M = [  # outline of the M, clockwise from the left stem's foot
    (357, 805), (357, 455), (370, 422), (405, 410), (433, 418),
    (627, 565),
    (822, 418), (850, 410), (885, 422), (897, 455),
    (897, 812), (885, 845), (860, 862), (806, 892), (800, 884),
    (800, 598), (790, 585),
    (650, 682), (627, 690), (604, 682),
    (465, 585), (455, 598),
    (455, 884), (449, 892), (395, 862), (368, 842),
]
BARS = [  # bottoms run parallel to the M's V, with a gap above it
    [(538, 440), (550, 425), (580, 413), (587, 422), (587, 508), (578, 512), (538, 474)],
    [(612, 395), (624, 380), (652, 372), (662, 382), (662, 512), (640, 532), (627, 536), (612, 526)],
    [(684, 362), (696, 346), (724, 337), (734, 348), (734, 458), (684, 495)],
]
WALLET = [
    (475, 722), (488, 705), (500, 703), (545, 722), (762, 660), (775, 665), (781, 690),
    (781, 718), (660, 742), (650, 760), (650, 815), (662, 832), (760, 855),
    (632, 915), (610, 912), (488, 857), (475, 838),
]
CLASP = [(660, 750), (672, 735), (775, 723), (785, 735), (785, 822), (772, 835), (672, 830), (660, 818)]
CLASP_DOT = (713, 790, 24)  # cx, cy, r

# --- Placement in the 108dp canvas --------------------------------------
# Content spans x 357..897, y 337..915; centre it and keep it inside the
# 66dp safe circle (about 58dp tall).
cx, cy = (357 + 897) / 2, (337 + 915) / 2
SCALE = 58 / (915 - 337)
TX, TY = 54 - cx * SCALE, 54 - cy * SCALE

WHITE = '#FFFFFF'
CYAN_TOP, CYAN_BOTTOM = '#2BE4F5', '#0EA5E9'
WALLET_TOP, WALLET_BOTTOM = '#22D3EE', '#1D6FE0'
CLASP_FILL = '#0B3D8C'
BG_TOP_RIGHT, BG_MID, BG_BOTTOM_LEFT = '#4F46E5', '#14206B', '#0891B2'
NAVY = '#0B1026'


def path(points):
    head, *rest = points
    return f'M{head[0]},{head[1]}' + ''.join(f'L{x},{y}' for x, y in rest) + 'Z'


def circle(cx_, cy_, r):
    return (f'M{cx_ - r},{cy_}a{r},{r} 0,1 1,{2 * r},0'
            f'a{r},{r} 0,1 1,{-2 * r},0Z')


def gradient(top, bottom, y0, y1):
    return f'''
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="0" android:startY="{y0}"
                    android:endX="0" android:endY="{y1}"
                    android:startColor="{top}" android:endColor="{bottom}" />
            </aapt:attr>'''


def vector(body, comment):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by the icon script from the source artwork (see ADR 0021);
     shapes are in the artwork's pixels, scaled into the 108dp canvas. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{SCALE:.5f}"
        android:scaleY="{SCALE:.5f}"
        android:translateX="{TX:.4f}"
        android:translateY="{TY:.4f}">{body}
    </group>
</vector>
'''


def shape(d, fill=None, grad=None, stroke=None):
    attrs = f'\n            android:pathData="{d}"'
    if fill:
        attrs += f'\n            android:fillColor="{fill}"'
    if stroke:
        # A stroke of the same colour with round joins rounds the corners.
        attrs += (f'\n            android:strokeColor="{stroke}"'
                  '\n            android:strokeWidth="14"'
                  '\n            android:strokeLineJoin="round"')
    if grad:
        return f'\n        <path{attrs}>{grad}\n        </path>'
    return f'\n        <path{attrs} />'


def bars_path():
    return ''.join(path(b) for b in BARS)


# Foreground: white M, cyan bars, cyan-to-blue wallet with its clasp.
foreground = (
    shape(path(M), grad=gradient(WHITE, '#BFE0FF', 410, 892), stroke='#F2F8FF')
    + shape(bars_path(), grad=gradient(CYAN_TOP, CYAN_BOTTOM, 337, 547), stroke=CYAN_TOP)
    + shape(path(WALLET), grad=gradient(WALLET_TOP, WALLET_BOTTOM, 660, 915), stroke=WALLET_TOP)
    + shape(path(CLASP), fill=CLASP_FILL, stroke=CLASP_FILL)
    + shape(circle(*CLASP_DOT), fill=WHITE)
)
# Monochrome (themed icons, the notification icon): one colour, so only the
# M and the bars; the wallet would merge into the M.
monochrome = (
    shape(path(M), fill=WHITE, stroke=WHITE)
    + shape(bars_path(), fill=WHITE, stroke=WHITE)
)

background = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon background: the artwork's navy, deepening from violet at
     the top right to cyan at the bottom left, with two soft waves. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="108" android:startY="0"
                android:endX="0" android:endY="108"
                android:startColor="{BG_TOP_RIGHT}" android:centerColor="{BG_MID}"
                android:endColor="{BG_BOTTOM_LEFT}" />
        </aapt:attr>
    </path>
    <path
        android:fillColor="#33000A3D"
        android:pathData="M0,30C24,22 48,40 72,30S102,14 108,20V0H0Z" />
    <path
        android:fillColor="#40071660"
        android:pathData="M0,78C20,70 36,90 60,86S96,64 108,70V108H0Z" />
</vector>
'''

os.makedirs(os.path.join(RES, 'drawable'), exist_ok=True)
with open(os.path.join(RES, 'drawable', 'ic_launcher_foreground.xml'), 'w', newline='\n') as f:
    f.write(vector(foreground, 'Adaptive icon foreground: the white M, the rising cyan bars and the wallet.'))
with open(os.path.join(RES, 'drawable', 'ic_launcher_monochrome.xml'), 'w', newline='\n') as f:
    f.write(vector(monochrome, 'One-colour icon (Android 13 themed icons, the notification status bar): the M and the bars.'))
with open(os.path.join(RES, 'drawable', 'ic_launcher_background.xml'), 'w', newline='\n') as f:
    f.write(background)

# --- Previews --------------------------------------------------------------
S = 432  # preview size (4px per dp)


def to_px(points):
    return [((x * SCALE + TX) * S / 108, (y * SCALE + TY) * S / 108) for x, y in points]


def draw_layers(mono=False):
    img = Image.new('RGBA', (S, S))
    d = ImageDraw.Draw(img)
    # background gradient (diagonal, 3 stops)
    def lerp(a, b, t):
        return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))
    def hexc(h):
        return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
    tr, mid, bl = hexc(BG_TOP_RIGHT), hexc(BG_MID), hexc(BG_BOTTOM_LEFT)
    if not mono:
        for yy in range(S):
            for xx in range(0, S, 2):
                t = ((S - xx) + yy) / (2 * S)
                c = lerp(tr, mid, t * 2) if t < .5 else lerp(mid, bl, (t - .5) * 2)
                d.rectangle([xx, yy, xx + 1, yy], fill=c)
    else:
        d.rectangle([0, 0, S, S], fill=(40, 40, 40))
    w = int(14 * SCALE * S / 108)
    def poly(pts, fill):
        p = to_px(pts)
        d.polygon(p, fill=fill)
        d.line(p + [p[0]], fill=fill, width=w, joint='curve')
    poly(M, 'white')
    for b in BARS:
        poly(b, 'white' if mono else CYAN_TOP)
    if not mono:
        poly(WALLET, WALLET_TOP)
        poly(CLASP, CLASP_FILL)
        x, y, r = CLASP_DOT
        (px, py), = to_px([(x, y)])
        rr = r * SCALE * S / 108
        d.ellipse([px - rr, py - rr, px + rr, py + rr], fill='white')
    return img


def masked(img, radius_frac):
    mask = Image.new('L', img.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, *img.size], radius=int(img.size[0] * radius_frac), fill=255)
    out = Image.new('RGBA', img.size, (255, 255, 255, 0))
    out.paste(img, mask=mask)
    return out


os.makedirs(OUT, exist_ok=True)
src = Image.open(SRC).convert('RGBA')
# The artwork's squircle sits at about 157..1097 x 137..1117.
crop = src.crop((157, 140, 1097, 1080 + 37)).resize((S, S), Image.LANCZOS)
layers = draw_layers()
circle_mask = Image.new('L', (S, S), 0)
ImageDraw.Draw(circle_mask).ellipse([0, 0, S, S], fill=255)
circ = Image.new('RGBA', (S, S), (255, 255, 255, 0))
circ.paste(layers, mask=circle_mask)
sheet = Image.new('RGBA', (S * 4 + 60, S + 20), (230, 230, 230, 255))
for i, im in enumerate([crop, masked(layers, .22), circ, draw_layers(mono=True)]):
    sheet.paste(im, (10 + i * (S + 13), 10), im)
sheet.save(os.path.join(OUT, 'compare.png'))

# Legacy launcher PNGs (Android 7, before adaptive icons): the artwork itself,
# cropped to its squircle with transparent corners.
legacy = masked(src.crop((157, 137, 1097, 1077 + 40)), .22)
for folder, px in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
    legacy.resize((px, px), Image.LANCZOS).save(os.path.join(RES, f'mipmap-{folder}', 'ic_launcher.png'))
# A 512px copy for the store listing (6.8): docs/brand/ic_launcher_512.png.
legacy.resize((512, 512), Image.LANCZOS).save(os.path.join(OUT, 'ic_launcher_512.png'))
print('scale', SCALE, 'tx', TX, 'ty', TY)
